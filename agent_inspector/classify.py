NOTIFY_TAGS = ("<task-notification>", "<subagent_notification>")
OUTPUT_TAGS = ("<local-command-stdout>", "<local-command-stderr>", "<local-command-caveat>",
               "<bash-stdout>", "<bash-stderr>", "Caveat: The messages below were generated by the user while running local commands")
COMPACT_PREFIXES = ("This session is being continued from a previous conversation",)
HOOK_PREFIXES = ("Stop hook feedback:", "SubagentStop hook feedback:", "A session-scoped Stop hook",
                 "<user-prompt-submit-hook>")
INTERRUPT_PREFIX = "[Request interrupted by user"
AUTO_PREFIXES = ('<codex_internal_context source="goal"', "[SYSTEM DIRECTIVE:", "<heartbeat>")
RELAY_PREFIXES = ("<agentryx_inbox_injection>", "[AGENTRYX TEAM CHANNEL MESSAGE BATCH]")
EXPANSION_PREFIXES = ("[search-mode]", "[analyze-mode]", "[ultrawork-mode]", "[think-mode]", "<codex_internal_context")

_CMD_NAME = re.compile(r"<command-name>(.*?)</command-name>", re.S)
_CMD_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
_BASH_IN = re.compile(r"<bash-input>(.*?)</bash-input>", re.S)
_SR_SPLIT = re.compile(r"<system-reminder>", re.S)


def slash_text(t: str) -> str:
    m = _CMD_NAME.search(t)
    a = _CMD_ARGS.search(t)
    name = (m.group(1).strip() if m else "").strip()
    if name and not name.startswith("/"):
        name = "/" + name
    args = a.group(1).strip() if a else ""
    return (name + (" " + args if args else "")).strip() or t


def bash_text(t: str) -> str:
    m = _BASH_IN.search(t)
    return ("!" + m.group(1).strip()) if m else t


def claude_user_text_kind(t: str, *, is_meta: bool, is_compact: bool, okind: str | None,
                          psrc: str | None, is_sub: bool, sdk_client: bool) -> str:
    s = t.lstrip()
    if is_compact or s.startswith(COMPACT_PREFIXES):
        return "compaction_summary"
    if s.startswith(INTERRUPT_PREFIX):
        return "interrupt_marker"
    if s.startswith(HOOK_PREFIXES):
        return "hook_output"
    if s.startswith("<command-name>") or s.startswith("<command-message>"):
        return "command_expansion" if is_meta else "human_command"
    if s.startswith(OUTPUT_TAGS):
        return "command_output"
    if s.startswith("<bash-input>"):
        return "human_shell"
    if s.startswith(NOTIFY_TAGS) or okind == "task-notification":
        return "task_notification"
    if s.startswith("<system-reminder>"):
        return "system_reminder"
    if s.startswith(AUTO_PREFIXES):
        return "auto_continuation"
    if s.startswith(RELAY_PREFIXES):
        return "relayed_prompt"
    if s.startswith(EXPANSION_PREFIXES):
        return "command_expansion"
    # origin.kind is set by the client and outranks isMeta (peer/coordinator messages are also isMeta)
    if okind in ("peer", "coordinator"):
        return "peer_message"
    if okind == "auto-continuation":
        return "auto_continuation"
    if is_meta:
        if s.startswith("Base directory for this skill"):
            return "command_expansion"
        return "meta"
    if s.startswith(INJECT_TAGS):
        return "context_injection"
    if is_sub:
        return "agent_prompt"
    if okind == "human":
        return "human"
    if okind:  # unknown non-human origin kind
        return "meta"
    if psrc == "system":  # client-generated prompt (promptSource=system) without a more specific marker
        return "meta"
    if psrc == "sdk" or sdk_client:
        return "sdk_prompt"
    return "human"


def codex_user_text_kind(t: str, *, is_sub: bool, noninteractive: bool) -> str:
    s = t.lstrip()
    if s.startswith("<turn_aborted>") or s.startswith(INTERRUPT_PREFIX):
        return "interrupt_marker"
    # Claude-format content inside Codex threads (sessions imported from Claude)
    if s.startswith(COMPACT_PREFIXES):
        return "compaction_summary"
    if s.startswith("<command-name>") or s.startswith("<command-message>"):
        return "human_command"
    if s.startswith(OUTPUT_TAGS):
        return "command_output"
    if s.startswith(HOOK_PREFIXES):
        return "hook_output"
    if s.startswith("<user_shell_command>"):
        return "human_shell"
    if s.startswith(NOTIFY_TAGS):
        return "task_notification"
    if s.startswith("<skill>"):
        return "command_expansion"
    if s.startswith(AUTO_PREFIXES):
        return "auto_continuation"
    if s.startswith(RELAY_PREFIXES):
        return "relayed_prompt"
    if s.startswith(EXPANSION_PREFIXES):
        return "command_expansion"
    if s.startswith(INJECT_TAGS):
        return "context_injection"
    if s.startswith("<system-reminder>"):
        return "system_reminder"
    if is_sub:
        return "agent_prompt"
    if noninteractive:
        return "sdk_prompt"
    return "human"


SPLITTABLE = ("human", "sdk_prompt", "agent_prompt", "system_reminder")


def classify_split(t: str, fn) -> list[tuple[str, str]]:
    """Classify text with fn; if it is prompt-like or starts with a reminder and contains <system-reminder>
    blocks, split them off and classify the remaining chunks separately. Returns [(kind, chunk)]."""
    k = fn(t)
    if k not in SPLITTABLE or "<system-reminder>" not in t:
        return [(k, t)]
    return [("system_reminder", c) if rem else (fn(c), c) for c, rem in split_system_reminders(t)]


def split_system_reminders(t: str) -> list[tuple[str, bool]]:
    """Split text into [(chunk, is_reminder)] around <system-reminder>...</system-reminder> blocks."""
    if "<system-reminder>" not in t:
        return [(t, False)]
    out: list[tuple[str, bool]] = []
    pos = 0
    while True:
        i = t.find("<system-reminder>", pos)
        if i < 0:
            rest = t[pos:]
            if rest.strip():
                out.append((rest, False))
            break
        if t[pos:i].strip():
            out.append((t[pos:i], False))
        j = t.find("</system-reminder>", i)
        j = len(t) if j < 0 else j + len("</system-reminder>")
        out.append((t[i:j], True))
        pos = j
    return out
